language plpgsql
security definer
set search_path=public,auth,pg_temp
as $$
declare
  uid uuid:=auth.uid();
  normalized_category text:=upper(btrim(coalesce(ticket_category,'OTHER')));
  ticket_id bigint;
  email_value citext;
begin
  if uid is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;
  if normalized_category not in ('ACCOUNT','CONTENT','BUG','MODERATION','PRIVACY','BILLING','SUGGESTION','OTHER') then
    raise exception 'INVALID_CATEGORY';
  end if;
  if char_length(btrim(coalesce(ticket_subject,''))) not between 4 and 180 then
    raise exception 'INVALID_SUBJECT';
  end if;
  if char_length(btrim(coalesce(ticket_body,''))) not between 10 and 12000 then
    raise exception 'INVALID_BODY';
  end if;

  perform public.consume_rate_limit(uid,'SUPPORT_TICKET',4,3600,ticket_subject);

  select u.email::citext into email_value from auth.users u where u.id=uid;

  insert into public.support_tickets(
    requester_id,contact_email,category,subject
  )
  values(
    uid,email_value,normalized_category,btrim(ticket_subject)
  )
  returning id into ticket_id;

  insert into public.support_ticket_messages(ticket_id,author_id,author_role,body)
  values(ticket_id,uid,'USER',btrim(ticket_body));

  insert into public.audit_log(actor_user_id,action,entity_type,entity_id,metadata)
  values(uid,'SUPPORT_TICKET_CREATED','SUPPORT_TICKET',null,
    jsonb_build_object('ticket_id',ticket_id,'category',normalized_category));

  return ticket_id;
end;
$$;

