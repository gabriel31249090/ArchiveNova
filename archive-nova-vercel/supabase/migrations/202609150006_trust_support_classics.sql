create or replace function public.get_support_ticket(target_ticket bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path=public,auth,pg_temp
as $$
declare result jsonb;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;

  select jsonb_build_object(
    'ticket',jsonb_build_object(
      'id',t.id,
      'code','AN-'||lpad(t.id::text,6,'0'),
      'category',t.category,
      'priority',t.priority,
      'status',t.status,
      'subject',t.subject,
      'assigned_to',t.assigned_to,
      'created_at',t.created_at,
      'updated_at',t.updated_at
    ),
    'messages',coalesce((
      select jsonb_agg(jsonb_build_object(
        'id',m.id,
        'author_role',m.author_role,
        'author_username',p.username::text,
        'author_display_name',coalesce(p.display_name,p.username::text),
        'body',m.body,
        'created_at',m.created_at
      ) order by m.created_at)
      from public.support_ticket_messages m
      left join public.profiles p on p.id=m.author_id
      where m.ticket_id=t.id
    ),'[]'::jsonb)
  )
  into result
  from public.support_tickets t
  where t.id=target_ticket
    and (t.requester_id=auth.uid() or public.is_staff());

  if result is null then raise exception 'TICKET_NOT_FOUND' using errcode='P0002'; end if;
  return result;
end;
$$;

create or replace function public.reply_support_ticket(
  target_ticket bigint,
  message_body text
)
returns bigint
language plpgsql
security definer
set search_path=public,auth,pg_temp
as $$
declare
  uid uuid:=auth.uid();
  staff boolean;
  owner boolean;
  next_id bigint;
  current_status text;
begin
  if uid is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;
  if char_length(btrim(coalesce(message_body,''))) not between 1 and 12000 then raise exception 'INVALID_BODY'; end if;

  staff:=public.is_staff();

  select t.requester_id=uid,t.status
  into owner,current_status
  from public.support_tickets t
  where t.id=target_ticket;

  if coalesce(owner,false)=false and not staff then raise exception 'NO_ACCESS' using errcode='42501'; end if;
  if current_status='CLOSED' and not staff then raise exception 'TICKET_CLOSED'; end if;

  perform public.consume_rate_limit(uid,'SUPPORT_REPLY',12,3600,message_body);

  insert into public.support_ticket_messages(ticket_id,author_id,author_role,body)
  values(target_ticket,uid,case when staff then 'STAFF' else 'USER' end,btrim(message_body))
  returning id into next_id;

  update public.support_tickets
  set last_message_at=now(),
      status=case
        when staff then 'WAITING_USER'
        when status in ('RESOLVED','WAITING_USER') then 'OPEN'
        else status
      end,
      closed_at=null
  where id=target_ticket;

  return next_id;
end;
$$;

create or replace function public.support_staff_queue(
  status_filter text default null,
  limit_count integer default 100
)
returns jsonb
language plpgsql
stable
security definer
set search_path=public,auth,pg_temp
as $$
begin
  if not public.is_staff() then raise exception 'STAFF_ONLY' using errcode='42501'; end if;

  return coalesce((
    select jsonb_agg(to_jsonb(x) order by x.priority_rank,x.last_message_at desc)
    from (
      select
        t.id,
        'AN-'||lpad(t.id::text,6,'0') code,
        t.category,t.priority,t.status,t.subject,t.assigned_to,
        t.last_message_at,t.created_at,
        p.username::text requester_username,
        coalesce(p.display_name,p.username::text) requester_display_name,
        a.username::text assigned_username,
        case t.priority when 'URGENT' then 1 when 'HIGH' then 2 when 'NORMAL' then 3 else 4 end priority_rank,
        (select count(*) from public.support_ticket_messages m where m.ticket_id=t.id) message_count
      from public.support_tickets t
      join public.profiles p on p.id=t.requester_id
      left join public.profiles a on a.id=t.assigned_to
      where status_filter is null or upper(status_filter)=t.status
      order by priority_rank,t.last_message_at desc
      limit greatest(1,least(coalesce(limit_count,100),250))
    ) x
  ),'[]'::jsonb);
end;
$$;

create or replace function public.support_staff_update_ticket(
  target_ticket bigint,
  next_status text default null,
  next_priority text default null,
  assign_to_self boolean default false
)
returns void
language plpgsql
security definer
set search_path=public,auth,pg_temp
as $$
declare
  normalized_status text:=upper(nullif(btrim(coalesce(next_status,'')),''));
  normalized_priority text:=upper(nullif(btrim(coalesce(next_priority,'')),''));
begin
  if not public.is_staff() then raise exception 'STAFF_ONLY' using errcode='42501'; end if;

  if normalized_status is not null and normalized_status not in ('OPEN','WAITING_USER','IN_PROGRESS','RESOLVED','CLOSED') then
    raise exception 'INVALID_STATUS';
  end if;
  if normalized_priority is not null and normalized_priority not in ('LOW','NORMAL','HIGH','URGENT') then
    raise exception 'INVALID_PRIORITY';
  end if;

  update public.support_tickets
  set status=coalesce(normalized_status,status),
      priority=coalesce(normalized_priority,priority),
      assigned_to=case when assign_to_self then auth.uid() else assigned_to end,
      closed_at=case
        when normalized_status in ('RESOLVED','CLOSED') then now()
        when normalized_status is not null then null
        else closed_at
      end,
      updated_at=now()
  where id=target_ticket;

  if not found then raise exception 'TICKET_NOT_FOUND' using errcode='P0002'; end if;

  insert into public.audit_log(actor_user_id,action,entity_type,entity_id,metadata)
  values(auth.uid(),'SUPPORT_TICKET_UPDATED','SUPPORT_TICKET',null,
    jsonb_build_object(
      'ticket_id',target_ticket,'status',normalized_status,
      'priority',normalized_priority,'assign_to_self',assign_to_self
    ));
end;
$$;

